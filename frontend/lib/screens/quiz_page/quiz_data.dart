// // lib/data/quiz_data.dart
class QuizQuestion {
  final int quizId;
  final String questionText;
  final String option1;
  final String option2;
  final String option3;
  final String option4;
  final int answer; // 正解の選択肢の番号 (1から始まる)
  final String explanation;

  QuizQuestion({
    required this.quizId,
    required this.questionText,
    required this.option1,
    required this.option2,
    required this.option3,
    required this.option4,
    required this.answer,
    required this.explanation,
  });

  // convenience getter to get options as a list
  List<String> get options => [option1, option2, option3, option4];

  // convenience getter to get 0-indexed correct option
  int get correctOptionIndex => answer - 1; // JSONのanswerは1から始まるため

  // ★★★ JSONからQuizQuestionオブジェクトを作成するファクトリコンストラクタ ★★★
  factory QuizQuestion.fromJson(Map<String, dynamic> json) {
    return QuizQuestion(
      quizId: json['quizId'] as int,
      questionText: json['questionText'] as String,
      option1: json['option1'] as String,
      option2: json['option2'] as String,
      option3: json['option3'] as String,
      option4: json['option4'] as String,
      answer: json['answer'] as int,
      explanation: json['explanation'] as String,
    );
  }
}

